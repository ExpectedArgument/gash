# ${#x} ${x#} ${x##} ${x%} ${x%%} with glob patterns
p="/usr/local/lib/file.tar.gz"
echo "c1: ${#p}"
echo "c2: ${p#*/}"
echo "c3: ${p##*/}"
echo "c4: ${p%.*}"
echo "c5: ${p%%.*}"
echo "c6: ${p#/usr}"
echo "c7: ${p%gz}"
echo "c8: ${p#nomatch}"
echo "c9: ${p##*.}"
echo "c10: ${p%/*}"
s="aaabbbccc"
echo "c11: ${s#a*b} ${s##a*b}"
echo "c12: ${s%b*c} ${s%%b*c}"
echo "c13: ${s#[ab]} ${s##[ab]*}"
echo "c14: ${s#?} ${s%??}"
pat="a*"
echo "c15: ${s#$pat} ${s#"$pat"}"
t="*star"
echo "c16: ${t#"*"} ${t#\*}"
echo "c17: ${s%%+(c)}"
shopt -s extglob
echo "c18: ${s%%+(c)} ${s##+(a)}"
shopt -u extglob
e=""
echo "c19: [${#e}] [${e#x}]"
unset u
echo "c20: [${#u}]"
set -- a bb ccc
echo "c21: ${#} ${#1} ${#3} ${#@} ${#*}"
arr=(one three five)
echo "c22: ${#arr} ${#arr[1]} ${#arr[@]}"
echo "c23: ${arr[@]#o} | ${arr[@]%e}"
echo "c24: ${@#?}"
w="  spaced  "
echo "c25: [${w#" "}] [${w% }]"
echo "c26: ${p#*[/.]} ${p%[/.]*}"
f="report.final.v2.txt"
echo "c27: name=${f%.*} ext=${f##*.} first=${f%%.*}"
n=12345
echo "c28: ${#n} ${n#12} ${n%45}"
q="a.b"
echo "c29: ${q#*.} ${q%.*} ${q#.} ${q%.}"
star="a*b*c"
echo "c30: ${star#*\*} ${star%\**}"
echo "c31: ${p##/*/}"
echo "c32: ${p#"/usr/local"}"
dir="path/to/dir/"
echo "c33: ${dir%/} ${dir%%/*}"
echo "c34: ${s#*} ${s##*}|"
echo "c35: ${s%*} [${s%%*}]"
br="[x]y"
echo "c36: ${br#\[x\]} ${br#"[x]"}"
