# case modification ${x^} ${x^^} ${x,} ${x,,} and declare -u/-l
s="hello World foo"
echo "c1: ${s^}"
echo "c2: ${s^^}"
echo "c3: ${s,}"
S="HELLO World"
echo "c4: ${S,,}"
echo "c5: ${S,}"
echo "c6: ${s^^[lo]}"
echo "c7: ${S,,[LW]}"
arr=(alpha beta gamma)
echo "c8: ${arr[@]^}"
echo "c9: ${arr[@]^^}"
set -- one two
echo "c10: ${@^} ${*^^}"
declare -u up="mixed Case"
echo "c11: $up"
up+=" more"
echo "c12: $up"
declare -l low="MiXeD"
echo "c13: $low"
low="AGAIN"
echo "c14: $low"
x="123abc"
echo "c15: ${x^^} ${x^}"
e=""
echo "c16: [${e^^}] [${e,}]"
echo "c17: ${s^[h]} ${s^[x]}"
echo "c18: ${s^^[a-m]}"
p="?"
echo "c19: ${s^^$p}"
name="john o'reilly"
echo "c20: ${name^}"
w="ALL CAPS"
lw=${w,,}; echo "c21: ${lw^}"
u="${s^^}"; echo "c22: ${u,,[A-H]}"
